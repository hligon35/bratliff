import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { pruneCss } from "./lib/css-prune.mjs";

const root = new URL("../", import.meta.url);
export const adminPages = ["store", "newsletter", "sponsors", "author", "analytics", "activity", "settings", "profile"];
const read = (name) => readFileSync(new URL(`assets/admin-src/${name}.js`, root), "utf8").replace(/\r\n/g, "\n");

export function buildBundle(page) {
  return [
    `/* Generated by scripts/build-admin-assets.mjs from assets/admin-src. Edit the sources, not this file. */`,
    "(function () {",
    read("core"),
    read(page),
    read("boot"),
    "})();",
    "",
  ].join("\n");
}

export function bundlePath(page) {
  return new URL(`assets/admin-${page}.js`, root);
}

export function buildStyles(page) {
  const source = readFileSync(new URL("assets/admin-src/admin.css", root), "utf8").replace(/\r\n/g, "\n");
  const corpus = ["admin/" + page + ".html", "assets/admin-" + page + ".js", "assets/admin-shell.js"]
    .map((path) => readFileSync(new URL(path, root), "utf8"))
    .join("\n");
  const banner = "/* Generated by scripts/build-admin-assets.mjs from assets/admin-src/admin.css, pruned to the markup of admin/" + page + ".html. Edit the source, not this file. */\n";
  return banner + pruneCss(source, corpus).css;
}

export function stylesPath(page) {
  return new URL(`assets/admin-${page}.css`, root);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const page of adminPages) {
    const targets = [[bundlePath(page), buildBundle(page)]];
    if (existsSync(new URL(`admin/${page}.html`, root))) targets.push([stylesPath(page), buildStyles(page)]);
    for (const [path, next] of targets) {
      const current = existsSync(path) ? readFileSync(path, "utf8").replace(/\r\n/g, "\n") : "";
      if (current === next) continue;
      stale += 1;
      if (!check) writeFileSync(path, next);
    }
  }
  if (check && stale) {
    console.error(`${stale} admin bundle(s) are out of date. Run npm run admin:build.`);
    process.exit(1);
  }
}